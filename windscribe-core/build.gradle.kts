import com.android.build.api.attributes.ProductFlavorAttr

/*
 * Packages the VPN core — :base plus every module it is built on — into a single
 * self-contained AAR that a partner UI (the equivalent of our :mobile / :tv modules)
 * sits on top of.
 *
 * The fused library plugin merges classes, resources, manifests, JNI, assets and
 * ProGuard rules from every `include` dependency and rewrites the embedded R classes,
 * so the consumer needs nothing from this repository beyond the AAR itself.
 *
 * Third-party dependencies (AndroidX, Room, OkHttp, ...) are deliberately NOT fused:
 * embedding them would collide with the consumer's own copies. The consumer declares them
 * itself; `./gradlew :windscribe-core:report` prints the exact list.
 *
 * Build with `./gradlew :windscribe-core:bundle`; the AAR lands in build/outputs/aar.
 * Nothing is published from here — CI can add maven-publish when we need a hosted artifact.
 */

plugins {
    id("com.android.fused-library")
}

androidFusedLibrary {
    namespace = "com.windscribe.core"
    minSdk {
        version = release(rootProject.extra["appMinSdk"] as Int)
    }
}

// The plugin pins the build type to `release` but says nothing about product flavors, so
// the flavored dependencies below cannot be resolved without naming the variant we want:
// `whitelabel` for :base and `skeleton` for :openvpn.
listOf(
    "include",
    "includeTransitiveResolvedApi",
    "includeTransitiveResolvedRuntime",
    "fusedApi",
    "fusedRuntime",
    "fusedSources",
).forEach { configurationName ->
    configurations.named(configurationName) {
        attributes {
            attribute(ProductFlavorAttr.of("dim"), objects.named(ProductFlavorAttr::class.java, "whitelabel"))
            attribute(ProductFlavorAttr.of("implementation"), objects.named(ProductFlavorAttr::class.java, "skeleton"))
        }
    }
}

dependencies {
    // Fusing is not transitive: every module that ends up inside the AAR is listed here.
    "include"(project(":base"))
    "include"(project(":openvpn"))
    "include"(project(":strongswan"))
    "include"(project(":common"))
    "include"(project(":wgtunnel"))
    "include"(group = "", name = "wsnet", ext = "aar")
}

// A partner only writes UI, so they should not have to transcribe the ~140 third-party
// coordinates the AAR expects the host app to supply. Those cannot be fused — the partner's own
// UI pulls AndroidX from Maven, and an embedded copy would collide with it class for class —
// so the AAR ships next to a generated Gradle snippet they apply in one line:
//
//     dependencies { implementation files('libs/windscribe-core.aar') }
//     apply from: 'windscribe-core-dependencies.gradle'
val generateConsumerDependencies =
    tasks.register("generateConsumerDependencies") {
        description = "Writes the dependency snippet that ships alongside windscribe-core.aar."
        dependsOn("report")
        val report = layout.buildDirectory.file("reports/fused_library_report/single/report.json")
        val snippet = layout.buildDirectory.file("outputs/aar/windscribe-core-dependencies.gradle")
        inputs.file(report)
        outputs.file(snippet)
        doLast {
            @Suppress("UNCHECKED_CAST")
            val parsed = groovy.json.JsonSlurper().parse(report.get().asFile) as Map<String, Any>
            val coordinates =
                (parsed["dependencies"] as List<String>)
                    // BOMs are pom-only and cannot be declared as a normal dependency.
                    .filterNot { it.substringAfter(':').substringBefore(':').endsWith("-bom") }
            snippet.get().asFile.writeText(
                buildString {
                    appendLine("// Generated by :windscribe-core — do not edit.")
                    appendLine("// Third-party dependencies windscribe-core.aar expects the host app to provide.")
                    appendLine()
                    appendLine("// logstash-logback-encoder drags in ch.qos.logback:logback-core, whose classes collide")
                    appendLine("// with logback-android. :base excludes it in its own build script; a bare AAR carries no")
                    appendLine("// metadata, so the exclusion has to be repeated here.")
                    appendLine("configurations.configureEach {")
                    appendLine("    exclude group: 'ch.qos.logback', module: 'logback-core'")
                    appendLine("}")
                    appendLine()
                    appendLine("dependencies {")
                    coordinates.forEach { appendLine("    implementation '$it'") }
                    appendLine("}")
                },
            )
        }
    }

tasks.named("bundle") {
    finalizedBy(generateConsumerDependencies)
}
